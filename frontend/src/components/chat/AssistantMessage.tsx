"use client";

import { BookOpen, ExternalLink } from "lucide-react";
import Link from "next/link";
import { useState } from "react";
import { api } from "@/lib/api";
import type { Itinerary, ItineraryOperation, ItineraryPlan, MessageMeta } from "@/lib/types";
import { CitationList, EvidenceBadge } from "../Citations";
import { RichText } from "../RichText";
import { BlockView, ClarifyChips } from "../blocks/InfoBlocks";
import { ItineraryView } from "../blocks/ItineraryView";
import { PlaceCards } from "../blocks/PlaceCards";
import { Badge, Notice } from "../ui";

const MODE_LABEL: Record<string, { label: string; tip: string }> = {
  llm: { label: "AI-written from sources", tip: "Generated by the configured language model using only the cited passages." },
  extractive: { label: "Quoted from sources", tip: "No language model configured: sentences are quoted directly from the indexed passages." },
  template: { label: "Structured result", tip: "Built from provider/planner data, not generated text." },
};

function InlineItinerary({ id, initialPlan, initialVersion, title }:
  { id: string; initialPlan: ItineraryPlan; initialVersion: number; title: string }) {
  const [plan, setPlan] = useState(initialPlan);
  const [version, setVersion] = useState(initialVersion);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const apply = async (ops: ItineraryOperation[]) => {
    setBusy(true);
    setError(null);
    try {
      const it = await api<Itinerary>(`/api/itineraries/${id}`, {
        method: "PATCH", body: JSON.stringify({ operations: ops, expected_version: version }),
      });
      setPlan(it.plan);
      setVersion(it.version);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="space-y-2 rounded-xl border border-border bg-background p-3">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <h3 className="font-display text-lg font-semibold">{title}</h3>
        <Link href={`/plan?id=${id}`} className="inline-flex items-center gap-1 text-sm text-primary hover:underline">
          Open in planner <ExternalLink className="h-3.5 w-3.5" aria-hidden />
        </Link>
      </div>
      {error && <Notice tone="error">{error}</Notice>}
      <ItineraryView plan={plan} editor={{ apply, busy }} showMap={false} />
    </div>
  );
}

export function AssistantMessage({ content, meta, streaming, onPick, disabled }:
  { content: string; meta?: MessageMeta; streaming?: boolean; onPick: (text: string) => void; disabled?: boolean }) {
  const [highlight, setHighlight] = useState<string | null>(null);
  const [showSources, setShowSources] = useState(true);
  const citations = meta?.citations ?? [];
  const mode = meta?.answer_mode && meta.answer_mode !== "none" ? MODE_LABEL[meta.answer_mode] : null;

  const onCite = (id: string) => {
    setShowSources(true);
    setHighlight(id);
    requestAnimationFrame(() => document.getElementById(`cite-${id}`)?.scrollIntoView({ behavior: "smooth", block: "nearest" }));
  };

  return (
    <div className="space-y-3">
      {content ? (
        streaming
          ? <p className="whitespace-pre-wrap leading-relaxed">{content}<span className="ml-0.5 inline-block h-4 w-1.5 animate-pulse bg-primary align-text-bottom" aria-hidden /></p>
          : <RichText text={content} citations={citations} onCite={onCite} />
      ) : streaming ? <p className="text-muted" role="status">Thinking…</p> : null}

      {!streaming && meta && (
        <>
          {(meta.blocks ?? []).map((b, i) => {
            if (b.type === "places") return <PlaceCards key={i} result={b.result} />;
            if (b.type === "itinerary") {
              return <InlineItinerary key={`${b.itinerary_id}-${b.version}`} id={b.itinerary_id} initialPlan={b.plan}
                                      initialVersion={b.version} title={b.title} />;
            }
            if (b.type === "clarify") return null; // rendered with suggestions below
            return <BlockView key={i} block={b} onPick={onPick} disabled={disabled} />;
          })}

          {(meta.notices ?? []).filter((n) => !content.includes(n)).map((n) => <Notice key={n} tone="info">{n}</Notice>)}

          {(mode || meta.evidence) && (
            <div className="flex flex-wrap items-center gap-1.5">
              {mode && <Badge title={mode.tip}>{mode.label}</Badge>}
              {citations.length > 0 && <EvidenceBadge evidence={meta.evidence} />}
            </div>
          )}

          {citations.length > 0 && (
            <div>
              <button type="button" onClick={() => setShowSources(!showSources)} aria-expanded={showSources}
                      className="mb-1.5 inline-flex items-center gap-1 text-sm font-medium text-muted hover:text-foreground">
                <BookOpen className="h-4 w-4" aria-hidden /> Sources ({citations.length})
              </button>
              {showSources && <CitationList citations={citations} highlighted={highlight} />}
            </div>
          )}

          <ClarifyChips options={meta.suggestions ?? []} onPick={onPick} disabled={disabled} />
        </>
      )}
    </div>
  );
}
